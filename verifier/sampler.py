"""
Speculative Acceptance Sampling Algorithms.
Implements Greedy Tree Verification and Stochastic Residual Distribution Matching.
"""

from typing import List, Tuple, Optional, Dict
import torch
import torch.nn.functional as F
from tree.node import SpeculativeTree


class VerificationResult:
    """
    Encapsulates the outcome of a speculative verification step.
    """

    def __init__(
        self,
        accepted_token_ids: List[int],
        accepted_node_ids: List[int],
        bonus_token_id: int,
        rejection_node_id: Optional[int] = None,
    ):
        self.accepted_token_ids = accepted_token_ids
        self.accepted_node_ids = accepted_node_ids
        self.bonus_token_id = bonus_token_id
        self.rejection_node_id = rejection_node_id

    @property
    def total_emitted_tokens(self) -> List[int]:
        """Returns accepted draft tokens plus the bonus token generated by the target model."""
        return self.accepted_token_ids + [self.bonus_token_id]

    @property
    def num_accepted(self) -> int:
        return len(self.accepted_token_ids)

    def __repr__(self) -> str:
        return (
            f"VerificationResult(accepted={self.accepted_token_ids}, "
            f"bonus={self.bonus_token_id}, count={self.num_accepted} + 1)"
        )


class GreedyTreeSampler:
    """
    Greedy tree verification:
    Finds the longest branch where every candidate token matches the target model's argmax.
    """

    @staticmethod
    def sample(
        tree: SpeculativeTree,
        target_logits_per_node: torch.Tensor,
        prefix_last_logits: torch.Tensor,
    ) -> VerificationResult:
        """
        Args:
            tree: SpeculativeTree with N nodes.
            target_logits_per_node: [N, V] target model logits computed at each tree node.
            prefix_last_logits: [V] target model logits computed at the last prefix token (evaluating root nodes).
        """
        N = len(tree)
        if N == 0:
            # No speculative tokens: standard single-token step
            bonus_token = int(torch.argmax(prefix_last_logits).item())
            return VerificationResult(
                accepted_token_ids=[],
                accepted_node_ids=[],
                bonus_token_id=bonus_token,
            )

        # Target top-1 predictions
        # For root nodes, their parent is the last prefix token -> evaluated by prefix_last_logits
        prefix_top1 = int(torch.argmax(prefix_last_logits).item())
        node_top1 = torch.argmax(target_logits_per_node, dim=-1).tolist()  # List of length N

        # Determine node acceptance
        # node_accepted[i] is True if all ancestors are accepted and its token matches parent's prediction
        node_accepted: Dict[int, bool] = {}

        # Sort nodes by depth so parents are processed before children
        nodes_by_depth = sorted(tree.nodes.values(), key=lambda n: n.depth)

        for node in nodes_by_depth:
            nid = node.node_id
            if node.parent_id is None:
                # Root node: must match prefix_top1
                node_accepted[nid] = (node.token_id == prefix_top1)
            else:
                # Child node: parent must be accepted, and token must match parent's prediction
                parent_acc = node_accepted.get(node.parent_id, False)
                parent_pred = node_top1[node.parent_id]
                node_accepted[nid] = parent_acc and (node.token_id == parent_pred)

        # Find the longest accepted path from any root to a leaf
        accepted_nodes = [nid for nid, acc in node_accepted.items() if acc]

        if not accepted_nodes:
            # Root rejection: 0 draft tokens accepted, emit prefix_top1 as bonus token
            return VerificationResult(
                accepted_token_ids=[],
                accepted_node_ids=[],
                bonus_token_id=prefix_top1,
                rejection_node_id=tree.root_ids[0] if tree.root_ids else None,
            )

        # Find accepted node with max depth
        best_node_id = max(accepted_nodes, key=lambda nid: tree.nodes[nid].depth)
        accepted_path = tree.get_path_from_root(best_node_id)
        accepted_tokens = [tree.nodes[nid].token_id for nid in accepted_path]

        # Bonus token is sampled from the last accepted node's prediction
        bonus_token = node_top1[best_node_id]

        return VerificationResult(
            accepted_token_ids=accepted_tokens,
            accepted_node_ids=accepted_path,
            bonus_token_id=bonus_token,
        )


class StochasticSpeculativeSampler:
    """
    Stochastic distribution-matching sampler (Leviathan et al., 2023).
    Ensures that the output text follows the exact target model distribution:
    P_accepted = min(1, P(x) / Q(x)).
    If rejected, resamples from max(0, P(x) - Q(x)).
    """

    @staticmethod
    def sample(
        tree: SpeculativeTree,
        target_logits_per_node: torch.Tensor,
        prefix_last_logits: torch.Tensor,
        temperature: float = 1.0,
    ) -> VerificationResult:
        N = len(tree)
        temp = max(1e-4, temperature)

        if N == 0:
            probs = F.softmax(prefix_last_logits / temp, dim=-1)
            bonus_token = int(torch.multinomial(probs, num_samples=1).item())
            return VerificationResult(
                accepted_token_ids=[],
                accepted_node_ids=[],
                bonus_token_id=bonus_token,
            )

        # Target probabilities
        prefix_probs = F.softmax(prefix_last_logits / temp, dim=-1)
        node_probs = F.softmax(target_logits_per_node / temp, dim=-1)

        # Traverse from root down the most probable accepted branch
        accepted_node_ids: List[int] = []
        accepted_tokens: List[int] = []
        bonus_token: Optional[int] = None
        rejection_node_id: Optional[int] = None

        # Level 0 (Roots)
        current_candidates = tree.root_ids
        parent_p_probs = prefix_probs

        while current_candidates:
            # Normalize draft probabilities among candidate paths at this depth
            q_probs = torch.tensor([tree.nodes[cid].draft_prob for cid in current_candidates], dtype=torch.float32)
            if q_probs.sum() > 0:
                q_probs = q_probs / q_probs.sum()
            else:
                q_probs = torch.full((len(current_candidates),), 1.0 / len(current_candidates))

            # Select candidate proportional to draft probability
            cand_idx = int(torch.multinomial(q_probs, num_samples=1).item())
            chosen_cid = current_candidates[cand_idx]
            node = tree.nodes[chosen_cid]
            token_id = node.token_id

            # Q(x) for chosen candidate
            q_x = float(q_probs[cand_idx].item())
            p_x = float(parent_p_probs[token_id].item())

            # Acceptance probability: min(1, P(x) / Q(x))
            alpha = min(1.0, p_x / max(q_x, 1e-6))
            r = float(torch.rand(1).item())

            if r < alpha:
                accepted_node_ids.append(chosen_cid)
                accepted_tokens.append(token_id)
                parent_p_probs = node_probs[chosen_cid]
                current_candidates = node.children_ids
            else:
                # Rejection: resample from normalized residual distribution max(0, P - Q)
                rejection_node_id = chosen_cid
                q_vec = torch.zeros_like(parent_p_probs)
                for idx, cid in enumerate(current_candidates):
                    q_vec[tree.nodes[cid].token_id] = q_probs[idx]

                residual = torch.clamp(parent_p_probs - q_vec, min=0.0)
                residual_sum = residual.sum()
                if residual_sum > 0:
                    resampled_probs = residual / residual_sum
                else:
                    resampled_probs = parent_p_probs

                bonus_token = int(torch.multinomial(resampled_probs, num_samples=1).item())
                break

        if bonus_token is None:
            # All candidates on branch accepted to the leaf!
            # Sample bonus token from the last accepted node's distribution
            last_id = accepted_node_ids[-1]
            last_probs = node_probs[last_id]
            bonus_token = int(torch.multinomial(last_probs, num_samples=1).item())

        return VerificationResult(
            accepted_token_ids=accepted_tokens,
            accepted_node_ids=accepted_node_ids,
            bonus_token_id=bonus_token,
            rejection_node_id=rejection_node_id,
        )
